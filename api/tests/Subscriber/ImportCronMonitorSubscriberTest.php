declare(strict_types=1);

namespace App\Tests\Subscriber;

use App\DataImport\ImportStatus;
use App\Entity\ImportEntity;
use App\Event\ImportFinishedEvent;
use App\Event\ImportStartedEvent;
use App\Schedule\ScheduleConfig;
use App\Subscriber\ImportCronMonitorSubscriber;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Sentry\CheckInStatus;
use Sentry\MonitorConfig;
use Sentry\State\HubInterface;
use Symfony\Component\Cache\Adapter\ArrayAdapter;
use Symfony\Component\Uid\Uuid;

final class ImportCronMonitorSubscriberTest extends TestCase
{
    /**
     * @var list<array{string, CheckInStatus, ?MonitorConfig, ?string}> slug, status, config and id of each check-in
     */
    private array $checkIns = [];
    private ArrayAdapter $store;

    #[\Override]
    protected function setUp(): void
    {
        $this->store = new ArrayAdapter();
    }

    public function testStartedImportOpensACheckInOfTheScheduledUpdate(): void
    {
        $import = $this->anImport();

        $this->subscriber()->onImportStarted(new ImportStartedEvent($import));

        [[$slug, $status, $config]] = $this->checkIns;
        $this->assertSame('update-data-sources', $slug);
        $this->assertSame(CheckInStatus::inProgress(), $status);
        $this->assertSame('30 2 * * *', $config->getSchedule()->getValue());
        $this->assertSame(240, $config->getMaxRuntime());
        $this->assertSame('check-in-id', $this->store->getItem($import->getId()->toRfc4122())->get());
    }

    #[DataProvider('endings')]
    public function testEndedImportClosesItsCheckInOnce(ImportStatus $status, CheckInStatus $checkIn): void
    {
        $import     = $this->anImport();
        $subscriber = $this->subscriber();

        $subscriber->onImportStarted(new ImportStartedEvent($import));
        $this->checkIns = [];

        $import->setStatus($status);
        $subscriber->onImportFinished(new ImportFinishedEvent($import));
        $subscriber->onImportFinished(new ImportFinishedEvent($import));

        $this->assertEquals([['update-data-sources', $checkIn, null, 'check-in-id']], $this->checkIns);
        $this->assertFalse($this->store->hasItem($import->getId()->toRfc4122()));
    }

    public static function endings(): iterable
    {
        yield 'succeeded' => [ImportStatus::Succeeded, CheckInStatus::ok()];
        yield 'failed' => [ImportStatus::Failed, CheckInStatus::error()];
        yield 'superseded' => [ImportStatus::Superseded, CheckInStatus::error()];
    }

    public function testNothingIsReportedWithoutSentry(): void
    {
        $import     = $this->anImport();
        $subscriber = $this->subscriber(checkInId: null);

        $subscriber->onImportStarted(new ImportStartedEvent($import));
        $import->setStatus(ImportStatus::Succeeded);
        $subscriber->onImportFinished(new ImportFinishedEvent($import));

        // only the attempt to open one, which a hub without a client ignores
        $this->assertCount(1, $this->checkIns);
        $this->assertFalse($this->store->hasItem($import->getId()->toRfc4122()));
    }

    private function subscriber(?string $checkInId = 'check-in-id'): ImportCronMonitorSubscriber
    {
        $hub = $this->createStub(HubInterface::class);
        $hub->method('captureCheckIn')->willReturnCallback(
            function (
                string $slug,
                CheckInStatus $status,
                $duration = null,
                ?MonitorConfig $config = null,
                ?string $id = null,
            ) use ($checkInId): ?string {
                $this->checkIns[] = [$slug, $status, $config, $id];

                return $checkInId;
            }
        );

        return new ImportCronMonitorSubscriber($hub, new ScheduleConfig(
            updateDataSources: '30 2 * * *',
            federationCheck: '* * * * *',
            federationCleanup: '0 0 * * *',
            collectStaleData: '0 6 * * *',
            recordDepartures: '20 seconds',
        ), $this->store);
    }

    private function anImport(): ImportEntity
    {
        $import = new ImportEntity();
        // The id is generated by Doctrine on persist, there is no setter.
        new \ReflectionProperty($import, 'id')->setValue($import, Uuid::v4());

        return $import;
    }
}
