declare(strict_types=1);

namespace App\Tests\DataImport;

use App\DataImport\MilestoneType;
use App\DataImport\ProgressReporterInterface;
use App\Entity\ImportEntity;
use App\Event\DataUpdateEvent;
use App\Provider\ZtmGdansk\ZtmGdanskConfig;
use App\Provider\ZtmGdansk\ZtmGdanskProvider;
use Doctrine\DBAL\Connection;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\Clock\MockClock;
use Symfony\Component\Uid\Uuid;

/**
 * Runs an importer against the test database, inside a transaction rolled back after each test.
 *
 * The ZTM Gdańsk provider row exists from the start, as ProviderDataImporter runs before every other importer.
 */
abstract class ImporterTestCase extends KernelTestCase
{
    protected const string PROVIDER = ZtmGdanskProvider::IDENTIFIER;
    protected const string NOW      = '2026-10-28 12:00:00';
    protected Connection $connection;

    /**
     * @var list<string>
     */
    protected array $warnings = [];

    /**
     * Totals reported with progress, the max argument of each call that had one.
     *
     * @var list<float>
     */
    protected array $progressTotals = [];

    #[\Override]
    protected function setUp(): void
    {
        self::bootKernel();

        $this->connection = self::getContainer()->get(Connection::class);
        $this->connection->beginTransaction();

        $this->connection->insert('provider', [
            'id'          => self::PROVIDER,
            'name'        => 'ZTM',
            'class'       => ZtmGdanskProvider::class,
            'update_date' => self::NOW,
        ]);
    }

    #[\Override]
    protected function tearDown(): void
    {
        $this->connection->rollBack();

        parent::tearDown();
    }

    /**
     * Starts a new import, as DataUpdater does before running the importers.
     */
    protected function newImport(): DataUpdateEvent
    {
        $import = new ImportEntity();
        // The id is generated by Doctrine on persist, there is no setter.
        new \ReflectionProperty($import, 'id')->setValue($import, Uuid::v4());

        $this->connection->insert(
            'import',
            [
                'id'         => $import->getId(),
                'started_at' => new \DateTime(self::NOW),
            ],
            [
                'id'         => 'uuid',
                'started_at' => 'datetime',
            ],
        );

        return new DataUpdateEvent($import);
    }

    /**
     * A reporter that records warnings into $warnings and progress totals into $progressTotals.
     */
    protected function reporter(): ProgressReporterInterface
    {
        $reporter = $this->createStub(ProgressReporterInterface::class);
        $reporter->method('subtask')->willReturnCallback(fn () => $this->reporter());
        $reporter->method('progress')->willReturnCallback(function (float $progress, ?float $max = null): void {
            if ($max !== null) {
                $this->progressTotals[] = $max;
            }
        });
        $reporter->method('milestone')->willReturnCallback(function (string $comment, MilestoneType $type = MilestoneType::Info): void {
            if ($type === MilestoneType::Warning) {
                $this->warnings[] = $comment;
            }
        });

        return $reporter;
    }

    /**
     * Rows of the table with only the given columns, ordered by the first one.
     *
     * @return list<array<string, mixed>>
     */
    protected function rows(string $table, string ...$columns): array
    {
        return $this->connection->createQueryBuilder()
            ->select(...$columns)
            ->from($table)
            ->orderBy($columns[0])
            ->executeQuery()
            ->fetchAllAssociative();
    }

    protected function clock(): MockClock
    {
        return new MockClock(self::NOW);
    }

    /**
     * Upstream addresses of the feeds, each distinct, so a stub streamer can tell them apart.
     */
    protected function config(): ZtmGdanskConfig
    {
        return new ZtmGdanskConfig(
            apiUrl: 'https://ztm.example/api',
            stopsUrl: 'https://ztm.example/stops',
            routesUrl: 'https://ztm.example/routes',
            tripsUrl: 'https://ztm.example/trips',
            stopsInTripsUrl: 'https://ztm.example/stops-in-trips',
            agenciesUrl: 'https://ztm.example/agencies',
            displaysUrl: 'https://ztm.example/displays',
        );
    }
}
