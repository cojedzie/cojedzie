declare(strict_types=1);

namespace App\Tests\Service;

use App\Dto\Status\Aggregated;
use App\Dto\Status\Time;
use App\Dto\Status\Version;
use App\Entity\Federation\FederatedConnectionEntity;
use App\Entity\Federation\FederatedServerEntity;
use App\Service\FederatedConnectionChecker;
use App\Service\FederatedConnectionUpdateFactory;
use App\Subscriber\FederationHeadersSubscriber;
use Carbon\Carbon;
use Doctrine\ORM\EntityManagerInterface;
use Ds\Seq;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\HttpClient\MockHttpClient;
use Symfony\Component\HttpClient\Response\MockResponse;
use Symfony\Component\Mercure\HubInterface;
use Symfony\Component\Serializer\SerializerInterface;
use Symfony\Component\Uid\Uuid;

final class FederatedConnectionCheckerTest extends KernelTestCase
{
    public function testSuccessfulCheckResetsConsecutiveFailures(): void
    {
        $connection = $this->connection(FederatedConnectionEntity::STATE_BACKOFF, failures: 3);

        $this->checker(new MockResponse($this->nodeStatus(), [
            'response_headers' => [
                FederationHeadersSubscriber::SERVER_ID_HEADER => $connection->getServer()->getId()->toRfc4122(),
            ],
        ]))->check($connection, force: true);

        $this->assertSame(FederatedConnectionEntity::STATE_READY, $connection->getState());
        $this->assertSame(0, $connection->getFailures());
        $this->assertSame(3, $connection->getFailuresTotal());
    }

    public function testMalformedServerIdIsAFailedCheck(): void
    {
        $connection = $this->connection(FederatedConnectionEntity::STATE_READY);

        $this->checker(new MockResponse($this->nodeStatus(), [
            'response_headers' => [
                FederationHeadersSubscriber::SERVER_ID_HEADER => 'not-a-uuid',
            ],
        ]))->check($connection, force: true);

        $this->assertSame(FederatedConnectionEntity::STATE_BACKOFF, $connection->getState());
        $this->assertSame(1, $connection->getFailures());
    }

    private function connection(string $state, int $failures = 0): FederatedConnectionEntity
    {
        $server = new FederatedServerEntity();
        $server->setId(Uuid::v4());

        $connection = FederatedConnectionEntity::createFromArray([
            'server'        => $server,
            'url'           => 'https://node.example',
            'state'         => $state,
            'failures'      => $failures,
            'failuresTotal' => $failures,
        ]);
        // The id is generated by Doctrine on persist, there is no setter.
        new \ReflectionProperty($connection, 'id')->setValue($connection, Uuid::v4());

        return $connection;
    }

    private function nodeStatus(): string
    {
        self::bootKernel();

        return self::getContainer()->get(SerializerInterface::class)->serialize(new Aggregated(
            time: Time::createFromDateTime(Carbon::parse('2026-10-28 12:00:00', 'Europe/Warsaw')),
            version: new Version(version: 'v2026.10.0', revision: 'abc'),
            endpoints: new Seq(),
        ), 'json');
    }

    private function checker(MockResponse $response): FederatedConnectionChecker
    {
        self::bootKernel();

        return new FederatedConnectionChecker(
            $this->createStub(EntityManagerInterface::class),
            new MockHttpClient($response),
            $this->createStub(HubInterface::class),
            self::getContainer()->get(FederatedConnectionUpdateFactory::class),
        );
    }
}
