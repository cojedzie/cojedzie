declare(strict_types=1);

namespace App\Tests\DataConverter;

use App\DataConverter\ConnectionConverter;
use App\Dto\Federation\Node;
use App\Dto\Status\Aggregated;
use App\Dto\Status\Endpoint;
use App\Dto\Status\Time;
use App\Dto\Status\Version;
use App\Entity\Federation\FederatedConnectionEntity;
use Carbon\Carbon;
use Ds\Seq;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\Serializer\SerializerInterface;
use Symfony\Component\Uid\Uuid;

/**
 * A federated node's endpoints come from the status the hub stored on its last check.
 */
final class ConnectionConverterTest extends KernelTestCase
{
    public function testNodeEndpointsComeFromTheStoredStatus(): void
    {
        $serializer = $this->serializer();

        $connection = $this->connection($serializer->serialize(
            $this->aggregated(new Seq([$this->endpoint('a'), $this->endpoint('b')])),
            'json'
        ));

        $endpoints = new ConnectionConverter($serializer)->convert($connection, Node::class)->getEndpoints()->toArray();

        $this->assertContainsOnlyInstancesOf(Endpoint::class, $endpoints);
        $this->assertSame(['a', 'b'], array_map(fn (Endpoint $endpoint) => $endpoint->getName(), $endpoints));
        $this->assertSame(['GET', 'POST'], $endpoints[1]->getMethods());
    }

    public function testNodeWithoutStoredStatusHasNoEndpoints(): void
    {
        $node = new ConnectionConverter($this->serializer())->convert($this->connection(null), Node::class);

        $this->assertTrue($node->getEndpoints()->isEmpty());
    }

    private function serializer(): SerializerInterface
    {
        self::bootKernel();

        return self::getContainer()->get(SerializerInterface::class);
    }

    private function connection(?string $lastStatus): FederatedConnectionEntity
    {
        $connection = FederatedConnectionEntity::createFromArray([
            'url'        => 'https://node.example',
            'lastStatus' => $lastStatus,
        ]);
        // The id is generated by Doctrine on persist, there is no setter.
        new \ReflectionProperty($connection, 'id')->setValue($connection, Uuid::v4());

        return $connection;
    }

    private function aggregated(Seq $endpoints): Aggregated
    {
        return new Aggregated(
            time: Time::createFromDateTime(Carbon::parse('2026-10-28 12:00:00', 'Europe/Warsaw')),
            version: new Version(version: 'v2026.10.0', revision: 'abc'),
            endpoints: $endpoints,
        );
    }

    private function endpoint(string $name): Endpoint
    {
        return Endpoint::createFromArray([
            'name'     => $name,
            'template' => "/api/v1/$name",
            'version'  => '1.0',
            'methods'  => ['GET', 'POST'],
        ]);
    }
}
